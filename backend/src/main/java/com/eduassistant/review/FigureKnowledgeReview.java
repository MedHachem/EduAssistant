package com.eduassistant.review;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.Table;
import jakarta.persistence.UniqueConstraint;
import java.time.Instant;

/**
 * One row = the CURRENT human review decision for one figure within one
 * chapter. Deliberately does NOT reference separate Figure or
 * KnowledgeItem JPA entities: both are owned/generated by the Python
 * pipeline + frontend (see data/output/final_figures/index.json and
 * data/output/knowledge/*.json) and have no other reason to exist as
 * rows in this database yet -- this table only stores the DECISION,
 * referencing those IDs as plain strings (see backend/README.md §3).
 *
 * Natural key is (chapterId, figureId): a figure_id like "figure_012"
 * repeats across chapters (Chapter 2 will also have a figure_001), so
 * chapterId is mandatory, not optional, for this to stay correct beyond
 * Chapter 1. documentId and pipelineRunId are deliberately NOT modeled
 * here -- see backend/README.md §6 for why.
 */
@Entity
@Table(
    name = "figure_knowledge_review",
    uniqueConstraints = @UniqueConstraint(name = "uk_chapter_figure", columnNames = {"chapter_id", "figure_id"})
)
public class FigureKnowledgeReview {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    @Column(name = "chapter_id", nullable = false, length = 128)
    private String chapterId;

    @Column(name = "figure_id", nullable = false, length = 64)
    private String figureId;

    /** Null when status == REJECTED (no item relates to this figure). */
    @Column(name = "knowledge_item_id", length = 128)
    private String knowledgeItemId;

    /** Optional, e.g. "illustrates" -- copied from the chosen candidate's
     * own relation at review time (see figure-association.model.ts). Not
     * required for persistence to work; purely useful context for later phases. */
    @Column(name = "relation", length = 64)
    private String relation;

    @Enumerated(EnumType.STRING)
    @Column(name = "status", nullable = false, length = 16)
    private ReviewStatus status;

    @Column(name = "reviewed_at", nullable = false)
    private Instant reviewedAt;

    /** No admin identity/auth system exists yet (see task brief §3) --
     * left nullable so it can be populated once one does, without a
     * migration. */
    @Column(name = "reviewed_by", length = 128)
    private String reviewedBy;

    protected FigureKnowledgeReview() {
        // JPA
    }

    public FigureKnowledgeReview(String chapterId, String figureId) {
        this.chapterId = chapterId;
        this.figureId = figureId;
    }

    public Long getId() {
        return id;
    }

    public String getChapterId() {
        return chapterId;
    }

    public String getFigureId() {
        return figureId;
    }

    public String getKnowledgeItemId() {
        return knowledgeItemId;
    }

    public void setKnowledgeItemId(String knowledgeItemId) {
        this.knowledgeItemId = knowledgeItemId;
    }

    public String getRelation() {
        return relation;
    }

    public void setRelation(String relation) {
        this.relation = relation;
    }

    public ReviewStatus getStatus() {
        return status;
    }

    public void setStatus(ReviewStatus status) {
        this.status = status;
    }

    public Instant getReviewedAt() {
        return reviewedAt;
    }

    public void setReviewedAt(Instant reviewedAt) {
        this.reviewedAt = reviewedAt;
    }

    public String getReviewedBy() {
        return reviewedBy;
    }

    public void setReviewedBy(String reviewedBy) {
        this.reviewedBy = reviewedBy;
    }
}
