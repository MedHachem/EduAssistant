import { HttpClient } from '@angular/common/http';
import { Injectable, inject } from '@angular/core';
import { Observable } from 'rxjs';
import { FigureReviewReport } from './figure-review.model';

/**
 * Loads the generated figure-candidate review report as a static asset.
 * scripts/sync-knowledge.mjs copies data/output/visual_elements_review.json
 * → public/figures/ and data/output/figure_candidates(_refined)/ → public/
 * (one-way, never written back).
 */
@Injectable({ providedIn: 'root' })
export class FigureReviewService {
  private readonly http = inject(HttpClient);

  load(file = 'visual_elements_review.json'): Observable<FigureReviewReport> {
    return this.http.get<FigureReviewReport>(`/figures/${file}`);
  }
}

/** image_path from the report (e.g. "figure_candidates_refined/page_013/...png") → served URL. */
export function cropUrl(imagePath: string | null | undefined): string | null {
  return imagePath ? `/${imagePath}` : null;
}

/**
 * The seed (pre-refinement) crop for the same candidate, for the optional
 * "compare seed / refined" view. Derived by path substitution rather than a
 * second index lookup: figure_candidates/ and figure_candidates_refined/ are
 * both generated by extract_figure_candidates.py from reports that share the
 * same candidate ordering, so "page_NNN/page_NNN_candidate_NN.png" is
 * identical under either directory.
 */
export function seedCropUrl(refinedImagePath: string | null | undefined): string | null {
  if (!refinedImagePath) return null;
  return `/${refinedImagePath.replace(/^figure_candidates_refined\//, 'figure_candidates/')}`;
}

/**
 * Whether a seed crop actually exists for this candidate's image path --
 * only round 1 (figure_candidates_refined/...) has a matching seed
 * directory (figure_candidates/...); round 3 (figure_candidates_v3/...)
 * has no separate seed extraction, so the compare toggle is hidden
 * rather than showing the same image twice.
 */
export function hasSeedCrop(imagePath: string | null | undefined): boolean {
  return !!imagePath && imagePath.startsWith('figure_candidates_refined/');
}
