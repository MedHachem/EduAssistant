import { Component, ViewEncapsulation, computed, inject, input } from '@angular/core';
import { DomSanitizer, SafeHtml } from '@angular/platform-browser';
import katex from 'katex';

export type Segment =
  | { kind: 'text'; value: string }
  | { kind: 'inline' | 'display'; value: string }
  | { kind: 'figure'; id: string | null; status: string | null; value: string };

const TOKEN =
  /\$\$([\s\S]+?)\$\$|\$([^$\n]+?)\$|<figure\b([^>]*)>([\s\S]*?)<\/figure>/g;

/** Splits generated content into plain text, $inline$ / $$display$$ math and <figure> tags. */
export function tokenize(text: string): Segment[] {
  const segments: Segment[] = [];
  let last = 0;
  for (const m of text.matchAll(TOKEN)) {
    if (m.index > last) segments.push({ kind: 'text', value: text.slice(last, m.index) });
    if (m[1] !== undefined) segments.push({ kind: 'display', value: m[1] });
    else if (m[2] !== undefined) segments.push({ kind: 'inline', value: m[2] });
    else {
      const attrs = m[3] ?? '';
      segments.push({
        kind: 'figure',
        id: /\bid="([^"]*)"/.exec(attrs)?.[1] ?? null,
        status: /\bstatus="([^"]*)"/.exec(attrs)?.[1] ?? null,
        value: m[4] ?? '',
      });
    }
    last = m.index + m[0].length;
  }
  if (last < text.length) segments.push({ kind: 'text', value: text.slice(last) });
  return segments;
}

function escapeHtml(s: string): string {
  return s
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

function renderMath(tex: string, displayMode: boolean): string {
  // throwOnError: false → invalid LaTeX is shown in red instead of breaking the page.
  return katex.renderToString(tex, { displayMode, throwOnError: false, output: 'html' });
}

/**
 * Minimal Markdown for chat answers, applied to already-escaped text only:
 * **bold**, `code`, "- " bullets and "#" headings at line start.
 */
function renderLightMarkdown(escaped: string, startsLine: boolean): string {
  return escaped
    .split('\n')
    .map((line, i) => {
      if (i > 0 || startsLine) {
        const heading = /^#{1,6} (.*)$/.exec(line);
        if (heading) return `<strong class="md-heading">${heading[1]}</strong>`;
        line = line.replace(/^(\s*)[-*] /, '$1• ');
      }
      return line;
    })
    .join('\n')
    .replace(/\*\*(.+?)\*\*/g, '<strong>$1</strong>')
    .replace(/`([^`\n]+)`/g, '<code>$1</code>');
}

export function renderToHtml(text: string, markdown = false): string {
  return tokenize(text)
    .map((seg, i, all) => {
      switch (seg.kind) {
        case 'text': {
          const escaped = escapeHtml(seg.value);
          return markdown ? renderLightMarkdown(escaped, i === 0 || all[i - 1].kind === 'display') : escaped;
        }
        case 'inline':
          return renderMath(seg.value, false);
        case 'display':
          return renderMath(seg.value, true);
        case 'figure': {
          const meta = [seg.id, seg.status].filter(Boolean).map((v) => escapeHtml(v!)).join(' · ');
          return `<span class="figure-tag"><span class="figure-tag-head">Figure${meta ? ` · ${meta}` : ''}</span>${renderToHtml(seg.value)}</span>`;
        }
      }
    })
    .join('');
}

/**
 * Displays generated text with LaTeX rendered by KaTeX, or — in raw mode — the exact
 * source string, untouched. Rendering never alters the underlying data.
 */
@Component({
  selector: 'app-math-text',
  template: `
    @if (raw()) {
      <pre class="math-raw">{{ text() }}</pre>
    } @else {
      <div class="math-rendered" [innerHTML]="html()"></div>
    }
  `,
  styleUrl: './math-text.scss',
  // Styles must reach the HTML generated by KaTeX / renderToHtml.
  encapsulation: ViewEncapsulation.None,
})
export class MathText {
  private readonly sanitizer = inject(DomSanitizer);

  readonly text = input.required<string>();
  readonly raw = input(false);
  /** Opt-in light Markdown (used by the chat; the admin review keeps the text as-is). */
  readonly markdown = input(false);

  // Safe to bypass: every non-math character is escaped above, and KaTeX output (trust: false) is plain markup.
  protected readonly html = computed<SafeHtml>(() =>
    this.sanitizer.bypassSecurityTrustHtml(renderToHtml(this.text(), this.markdown())),
  );
}
